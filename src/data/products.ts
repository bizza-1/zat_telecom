export const buildWhatsAppLink = (product: Product) => {
  const msg = encodeURIComponent(
    `Hello ZAT Telecom, I'm interested in the *${product.name}* (SKU: ${product.sku}) priced at ${formatPrice(product.price)}. Is it currently available?`
  );
  return `https://wa.me/${whatsappNumber}?text=${msg}`;
};
